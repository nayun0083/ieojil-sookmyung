# =========================================
# 유형 점수 계산
# =========================================

def calculate_type_scores(answers):

    # 처음에는 모든 유형 점수를 0으로 시작
    scores = {
        type_name: 0.0
        for type_name in TYPE_NAMES
    }

    # 질문별 상세 점수를 저장
    detail_scores = {}


    # Q1~Q4만 반복
    for question_key, weight in QUESTION_WEIGHTS.items():

        # 사용자가 선택한 답변
        answer = answers.get(question_key)

        if answer is None:
            continue


        # 해당 답변의 유형별 원점수
        option_scores = SCORING_TABLE[
            question_key
        ].get(answer)

        if option_scores is None:
            continue


        detail_scores[question_key] = {}


        # 4개 유형에 대해 계산
        for type_name in TYPE_NAMES:

            raw_score = option_scores[type_name]

            # 원점수 0~3을 0~1로 변환
            normalized_score = raw_score / 3

            # 질문별 가중치 적용
            weighted_score = (
                normalized_score
                * weight
                * 100
            )

            # 최종 점수에 누적
            scores[type_name] += weighted_score


            # 상세 결과 저장
            detail_scores[
                question_key
            ][type_name] = {
                "raw": raw_score,
                "weighted": weighted_score,
            }


    # 소수점 둘째 자리까지
    scores = {
        type_name: round(score, 2)
        for type_name, score in scores.items()
    }


    return scores, detail_scores


# =========================================
# 최종 유형 결정
# =========================================

def determine_type(scores):

    # 가장 높은 점수
    max_score = max(
        scores.values()
    )


    # 최고점인 유형 찾기
    candidates = [
        type_name
        for type_name, score in scores.items()
        if score == max_score
    ]


    # 최고점이 하나라면 그대로 반환
    if len(candidates) == 1:
        return candidates[0]


    # 동점일 경우
    # 현재는 유형 목록 순서를 기준으로 결정
    return candidates[0]


# =========================================
# 최종 결과 생성
# =========================================

def get_matching_result(answers):

    scores, detail_scores = calculate_type_scores(
        answers
    )


    result_type = determine_type(
        scores
    )


    return {
        "type": result_type,

        "title":
            f"{result_type} 유형이에요!",

        "desc":
            TYPE_DESCRIPTIONS[result_type],

        "emoji":
            TYPE_EMOJI[result_type],

        "scores":
            scores,

        "detail_scores":
            detail_scores,

        # Q5는 점수 계산하지 않고
        # 선택한 시간만 저장
        "available_time":
            answers.get("q5"),
    }
